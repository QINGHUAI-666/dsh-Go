package io.github.ccch1mneyyy.dsh_app.runtime

import android.system.Os
import java.io.File

/**
 * Writes the three files a Droidspaces container needs before it starts:
 *
 * * `opt/dsh-go/droidspaces-env.sh` — the guest environment DSH gets under
 *   PRoot, exported for PID 1. Contains credentials, so mode 0600.
 * * `opt/dsh-go/droidspaces-command.sh` — the composed `dsh web` command with
 *   every overlay (`--patch`) already applied.
 * * `opt/dsh-go/droidspaces-init.sh` — PID 1: export the environment, then
 *   replace itself with the command. DSH's exit ends the container.
 *
 * These live inside the existing app-private rootfs, so the current installer,
 * engine upgrade, safe-mode profile and reset paths keep owning the tree. The
 * container's root user reads them through the root manager.
 */
object DroidspacesGuest {
    const val DIR = "/opt/dsh-go"
    private const val ENV_FILE = "$DIR/droidspaces-env.sh"
    private const val COMMAND_FILE = "$DIR/droidspaces-command.sh"
    private const val INIT_FILE = "$DIR/droidspaces-init.sh"

    fun prepare(rootfs: File, env: Map<String, String>, command: String) {
        val directory = File(rootfs, DIR.removePrefix("/"))
        check(directory.isDirectory || directory.mkdirs()) { "cannot create $DIR in the runtime" }

        val envText = buildString {
            append("#!/bin/sh\n")
            append("# Generated by dsh-go. Credentials stay inside this rootfs.\n")
            for ((key, value) in env) {
                if (!ENV_NAME.matches(key)) continue
                append("export ").append(key).append('=').append(shellQuote(value)).append('\n')
            }
        }
        writeExecutable(File(rootfs, ENV_FILE.removePrefix("/")), envText, 0b110_000_000)
        writeExecutable(
            File(rootfs, COMMAND_FILE.removePrefix("/")),
            "#!/bin/sh\n# Generated by dsh-go: the composed dsh web command.\n$command\n",
            0b111_000_000,
        )
        writeExecutable(
            File(rootfs, INIT_FILE.removePrefix("/")),
            "#!/bin/sh\n" +
                "# dsh-go Droidspaces PID 1: environment, then the composed dsh web command.\n" +
                ". $ENV_FILE\n" +
                "exec /bin/sh $COMMAND_FILE\n",
            0b111_000_000,
        )
    }

    private fun writeExecutable(file: File, text: String, mode: Int) {
        file.writeText(text)
        runCatching { Os.chmod(file.absolutePath, mode) }
    }

    internal fun shellQuote(value: String): String = "'" + value.replace("'", "'\\''") + "'"

    private val ENV_NAME = Regex("^[A-Za-z_][A-Za-z0-9_]*$")
}
